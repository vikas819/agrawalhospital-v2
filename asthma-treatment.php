                                    <h4 class="title mb-20">Treatment and Diagnosis</h4>
                                    <div class="desc">
                                        Asthma may be evaluated by specialists such as allergists, pulmonologists, ENT specialists, and pediatricians. A chest examination is an important part of the assessment. Diagnostic methods may include spirometry and a methacholine challenge, along with analysis of expiratory flow rate. Spirometry is a commonly recommended test. A bronchodilator such as salbutamol may be used to assess changes in FEV1. A methacholine challenge measures airway response to an inhaled substance that can narrow the airways. Test results should be interpreted by a healthcare professional alongside symptoms and other clinical findings; a positive result may support an asthma diagnosis, while a negative result can make asthma less likely.
