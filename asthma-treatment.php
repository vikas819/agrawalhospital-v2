                                    <h3 class="title mb-20">
                                        Asthma Treatment
                                    </h3>
                                    <div class="desc">
                                        Asthma is a chronic disease involving the airways in the lungs. These airways, or bronchial tubes, allow air to move in and out of the lungs.
                                    </div>
                                    <div class="desc">
                                        With asthma, the airways are chronically inflamed. They can become more swollen, and the muscles around them can tighten when symptoms are triggered. This makes it harder for air to move in and out of the lungs and can cause coughing, wheezing, shortness of breath, and chest tightness.
                                    </div>
                                    <div class="desc">
                                        For many people with asthma, symptoms are closely related to physical activity. Some otherwise healthy people experience asthma symptoms only during exercise, a condition called exercise-induced bronchoconstriction (EIB), or exercise-induced asthma (EIA). Staying active is important for good health, and asthma does not have to keep you on the sidelines. Your physician can develop a management plan to help control symptoms before, during, and after physical activity.
